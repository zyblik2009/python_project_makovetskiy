#Даны две переменные целого типа: A и B. Если их значения не равны, то присвоить каждой переменной сумму этих значений, а если равны, то присвоить переменным нулевые значения. Вывести новые значения переменных A и B.
while True:
    a = input("Введите переменную A: ")
    try:
        a = int(a)
        break
    except ValueError:
        print("Число неккоректное")
while True:
    b = input("Введите переменную B: ")
    try:
        b = int(b)
        break
    except ValueError:
        print("Число неккоректное")
if a != b:
    c = a + b
    a = c
    b = c
    print("Числа не равны, переменным присвоены следующие значения:")
    print("A =", a)
    print("B =", b)
else:
    a = 0
    b = 0
    print("Числа равны, переменным присвоены нулевые значения:")
    print("A =", a)
    print("B =", b)
